alter table public.financeiro_lancamentos add column if not exists fornecedor text;
update public.financeiro_lancamentos set fornecedor = case
  when descricao ~* 'CEMIG' then 'CEMIG'
  when descricao ~* 'BLINK' then 'BLINK TELECOMUNICAÇÕES'
  when descricao ~* 'ALGAR' then 'ALGAR TELECOM'
  when descricao ~* 'INTERPOST' then 'INTERPOST EMPREENDIMENTOS'
  when descricao ~* 'TURBO ?SITE' then 'TURBOSITE'
  when descricao ~* 'CLARO.*VIVO|VIVO.*CLARO' then 'CLARO / VIVO'
  when descricao ~* 'VIVO' then 'VIVO'
  when descricao ~* 'CLARO' then 'CLARO'
  when descricao ~* 'UNIMED' then 'UNIMED'
  when descricao ~* 'THEMIS' then 'THEMIS RECORTES E TECNOLOGIA JURÍDICA'
  when descricao ~* 'EASY ?JUR' then 'EASY JUR TECNOLOGIAS'
  when descricao ~* 'CASA DAS IMPRESSORAS' then 'CASA DAS IMPRESSORAS'
  when descricao ~* 'GEOVANI' then 'GEOVANI (SERVIÇOS DE TI)'
  when descricao ~* 'CLAUDIO' then 'CLAUDIO (SERVIÇOS DE TI)'
  when descricao ~* 'MATUR' then 'MATUR'
  when descricao ~* 'H[IY]PERCHECK' then 'HIPERCHECK'
  when descricao ~* 'QUALICORP' then 'QUALICORP'
  when descricao ~* 'PORTO SEGURO' then 'PORTO SEGURO'
  when descricao ~* 'METROPOLITAN|METLIFE' then 'METLIFE'
  when descricao ~* 'MEETHUB' then 'MEETHUB'
  when descricao ~* 'MSM CONSULTORIA' then 'MSM CONSULTORIA E EMPREENDIMENTOS'
  when descricao ~* 'INTEGRIS' then 'CONTABILIDADE INTEGRIS'
  when descricao ~* 'OFFICIAL PUBLICA' then 'OFFICIAL PUBLICAÇÕES'
  when descricao ~* 'CONDOM[ÍI]NIO' then 'CONDOMÍNIO ED. STRAUSS'
  when descricao ~* 'GARAGENS AVULSAS' then 'ED. STRAUSS (GARAGENS)'
  when descricao ~* 'IPTU GARAGENS' then 'PREFEITURA (IPTU GARAGENS)'
  when descricao ~* 'ALUGUEL SALAS' then 'ED. STRAUSS (ALUGUEL DAS SALAS)'
  when descricao ~* 'PARCELA IPTU' then 'PREFEITURA (IPTU)'
  when descricao ~* 'ANUIDADE OAB/([A-Z]{2})' then 'OAB/' || upper(substring(descricao from '([A-Z]{2})'))
  when descricao ~* 'TFLF' then 'TFLF (TAXA DE FISCALIZAÇÃO)'
  when descricao ~* 'INPI' then 'INPI'
  when descricao ~* 'SIMPLES NACIONAL' then 'RECEITA FEDERAL (SIMPLES NACIONAL)'
  when descricao ~* '\yINSS\y' then 'INSS'
  when descricao ~* '\yFGTS\y' then 'FGTS'
  when descricao ~* 'FOLHA DE SAL[ÁA]RIOS' then 'FOLHA DE PAGAMENTO'
  when descricao ~* 'VALE TRANSPORTE.*LUANA' then 'LUANA (VALE TRANSPORTE)'
  when descricao ~* 'ALIMENTA[ÇC][ÃA]O.*LUANA|LUANA.*ALIMENTA' then 'LUANA (ALIMENTAÇÃO)'
  when descricao ~* 'PEDV DAY' then 'PEDV DAY (ALIMENTAÇÃO)'
  when descricao ~* 'TARIFA BANC' then 'BANCO BRADESCO (TARIFA)'
  when descricao ~* 'INDENIZA[ÇC][ÃA]O' then 'INDENIZAÇÃO (RESCISÃO)'
  else coalesce(nullif(trim(split_part(split_part(regexp_replace(descricao, '^((PAGAMENTO|PAGTO\.?|PGTO\.?|PAG\.?|REF\.?|DESP\.?|DESPESAS?|COM|COMPRA|DE|DA|DO|Á)\s+)+', '', 'i'), ' - ', 1), ' REF', 1)), ''), descricao) end
where tipo = 'despesa' and fornecedor is null and origem = 'planilha-contabil-2026';
select fornecedor, count(*) from public.financeiro_lancamentos where origem='planilha-contabil-2026' group by 1 order by 2 desc, 1;